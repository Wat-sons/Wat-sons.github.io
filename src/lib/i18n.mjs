/* ============================================================
   lib/i18n.mjs — 双语接线的唯一入口

   设计原则（用户 2026-10 定的规则）：

     **固定英文品牌层** —— 导航、区块标题、阶段标签、品牌名、
     Loading 文案、技术名词/平台名/官方赛事名，两种语言下都不变。
     这些**不进这个助手**，就照原样写死在模板里。

     **中英文内容层** —— 介绍、描述、说明、提示、无障碍标签，
     成对给出，由前端切换。

   用法：中文是**默认渲染进 HTML 的那一份**（首屏、SEO、无 JS 都靠它），
   英文只作为属性挂上去，切换时由 JS 换 textContent。
   所以页面上永远只有一份内容，不存在"复制整套 HTML"。

     <p${bi(zh, en)}>${esc(zh)}</p>

   约定：数据文件里成对的字段用 `X`（中文）与 `XEn`（英文）。
   英文缺失时 `bi()` 返回空串，该元素就固定显示中文 —— 不会出现空白。
   ============================================================ */

import { esc } from "./html.mjs";

/** 文本双语属性。en 为空 → 返回空串，元素保持中文不动。 */
export const bi = (zh, en) =>
  en ? ` data-zh="${esc(zh)}" data-en="${esc(en)}"` : "";

/** 带 title 属性的双语（页脚计时的说明文字就属于这种）。 */
export const biTitle = (zh, en) =>
  en ? ` data-zh-title="${esc(zh)}" data-en-title="${esc(en)}"` : "";

/** 内容里本来就带标签（比如 about 的 |高亮|）时用这个，切换时换 innerHTML。
    两边的 HTML 都是我们自己在构建期生成的，不涉及用户输入。 */
export const biHtml = (zh, en) =>
  en ? ` data-zh-html="${esc(zh)}" data-en-html="${esc(en)}"` : "";

/** 从成对字段里取英文，容忍缺失 */
export const en = (obj, key) => obj && obj[key + "En"] ? obj[key + "En"] : "";
